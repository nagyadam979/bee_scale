#!/usr/bin/env python3
"""A node-panel PREMADE breakout-moduljainak footprintjei a futo KiCad PCB
Editor-ba, az IPC API-n (kipy) at -- elrendezes-tervezeshez ("pakolashoz").

Minden modul egy FootprintInstance:
  - fizikai kontur = BoardRectangle a F.Silkscreen retegen (a modullal egyutt mozog),
  - a lab-padek atmeno-furatosak (PTH), ahol ismert a geometria.

A modulok szetszorva kerulnek a boardra, hogy ne fedjek egymast; utana a
felhasznalo szabadon tologatja oket (KiCad: 'M').

MERET-FORRAS es BIZTONSAG (2026-07, webkutatas + BOM):
  ESP32-C3 SuperMini  18 x 22,5 mm | 2x8 @2,54, sortav 15,24  | MAGAS
  HX711-M (piros)     16 x 24   mm | 6+4 @2,54, sortav ~13    | kontur kozepes, geom. ALACSONY
  TP4056-PROT-USB-C   17,3 x 29 mm | NEM raszter (3,4/7,6/3,4) | pad ALACSONY
  TPS63000-M          16 x 24   mm | sarok-padek + jumperek    | ALACSONY (nincs mech. rajz)
A 3 bizonytalan modul pad-geometriaja tolomeros bemeres utan finomitando.

Elofeltetel: fut a KiCad 10, IPC API be, ES nyitva egy board a (standalone) PCB
Editor-ban. A standalone pcbnew sajat socketet nyit (/tmp/kicad/api-<pid>.sock);
ezt auto-detektaljuk, mert a manager api.sock-ja nem ismeri a GetOpenDocuments-et.

Futtatas:
  python3 make_node_modules.py
"""

import glob
import sys

from kipy import KiCad
from kipy.errors import ApiError, ConnectionError as KiCadConnectionError
from kipy.board_types import (
    FootprintInstance, Pad, PadType, PadStackType, PadStackShape,
    DrillShape, BoardLayer, BoardRectangle,
)
from kipy.geometry import Vector2


def find_pcbnew_socket() -> str | None:
    """A standalone pcbnew per-PID socketje. A manager api.sock-ja nem jo."""
    socks = sorted(glob.glob("/tmp/kicad/api-*.sock"))
    if not socks:
        return None
    return "ipc://" + socks[0]


def tht_pad(number: str, x_mm: float, y_mm: float,
            pad_d_mm: float = 1.8, drill_d_mm: float = 1.0) -> Pad:
    """Kor alaku PTH pad (footprint-relativ pozicio)."""
    pad = Pad()
    pad.number = number
    pad.pad_type = PadType.PT_PTH
    pad.position = Vector2.from_xy_mm(x_mm, y_mm)
    ps = pad.padstack
    ps.type = PadStackType.PST_NORMAL
    fcu = ps.copper_layer(BoardLayer.BL_F_Cu)
    fcu.shape = PadStackShape.PSS_CIRCLE
    fcu.size = Vector2.from_xy_mm(pad_d_mm, pad_d_mm)
    ps.drill.shape = DrillShape.DS_CIRCLE
    ps.drill.diameter = Vector2.from_xy_mm(drill_d_mm, drill_d_mm)
    ps.drill.start_layer = BoardLayer.BL_F_Cu
    ps.drill.end_layer = BoardLayer.BL_B_Cu
    return pad


def silk_outline(w_mm: float, l_mm: float) -> BoardRectangle:
    """Kontur-teglalap a F.Silkscreen-en, a footprint origojara centralva."""
    r = BoardRectangle()
    r.top_left = Vector2.from_xy_mm(-w_mm / 2, -l_mm / 2)
    r.bottom_right = Vector2.from_xy_mm(w_mm / 2, l_mm / 2)
    r.layer = BoardLayer.BL_F_SilkS
    return r


def make_module(ref: str, value: str, pos_xy_mm, w_mm, l_mm, pads):
    """Egy modul-footprint osszeallitasa. pads: [(number, x, y[, pad_d, drill]), ...]."""
    fp = FootprintInstance()
    fp.reference_field.text.value = ref
    fp.value_field.text.value = value
    fp.layer = BoardLayer.BL_F_Cu               # KOTELEZO (kulonben csendben eldobja)
    fp.position = Vector2.from_xy_mm(*pos_xy_mm)
    fp.definition.add_item(silk_outline(w_mm, l_mm))
    for p in pads:
        num, x, y = p[0], p[1], p[2]
        pad_d = p[3] if len(p) > 3 else 1.8
        drill = p[4] if len(p) > 4 else 1.0
        fp.definition.add_item(tht_pad(num, x, y, pad_d, drill))
    return fp


# --- Lab-geometriak (footprint-relativ, mm; origo = kontur kozepe) ---

def esp32c3_pads():
    """2x8 @2,54, sortav 15,24. Sorok a hosszu (22,5) elek menten -> pad-ok Y-ban."""
    pads = []
    n = 1
    xs = (-7.62, 7.62)                      # sortav 15,24 -> +-7,62
    y0 = -(7 * 2.54) / 2                    # 8 pad, span 17,78, centralva
    for x in xs:
        for i in range(8):
            pads.append((str(n), x, y0 + i * 2.54))
            n += 1
    return pads


def hx711m_pads():
    """Analog 6 (egyik el) + digitalis 4 (masik el), @2,54, sortav ~13 (BECSLES)."""
    pads = []
    # analog oldal (6): x=-6,5
    y0a = -(5 * 2.54) / 2
    for i, name in enumerate(("E+", "E-", "A-", "A+", "B-", "B+")):
        pads.append((name, -6.5, y0a + i * 2.54))
    # digitalis oldal (4): x=+6,5
    y0d = -(3 * 2.54) / 2
    for i, name in enumerate(("GND", "DT", "SCK", "VCC")):
        pads.append((name, 6.5, y0d + i * 2.54))
    return pads


def tp4056_pads():
    """NEM raszter. USB-veg: IN+/IN- (2 pad); tulso veg: OUT+/B+/B-/OUT- (3,4/7,6/3,4)."""
    return [
        ("IN+", -7.1, -12.8), ("IN-", 7.1, -12.8),
        ("OUT+", -7.2, 12.8), ("B+", -3.8, 12.8),
        ("B-", 3.8, 12.8), ("OUT-", 7.2, 12.8),
    ]


def tps63000_pads():
    """4 sarok-tappad (nagyobb) + also konfig-jumperek (kis padek). BECSLES."""
    pads = [
        ("VIN", -5.5, -9.5, 2.2, 1.2), ("VOUT", 5.5, -9.5, 2.2, 1.2),
        ("GND1", -5.5, 9.5, 2.2, 1.2), ("GND2", 5.5, 9.5, 2.2, 1.2),
    ]
    # also el menti konfig-padek (EN/PS/5V/4V2/3V3/ADJ) ~1,8 pitch, kis pad
    cfg = ("EN", "PS", "5V", "4V2", "3V3", "ADJ")
    x0 = -(len(cfg) - 1) * 1.8 / 2
    for i, name in enumerate(cfg):
        pads.append((name, x0 + i * 1.8, 10.5, 1.2, 0.7))
    return pads


MODULES = [
    # ref,        value,                 kozeppont(mm),  Sz,    H,     padek
    ("ESP32C3",   "ESP32-C3 SuperMini",  (25, 25),       18.0,  22.5,  esp32c3_pads()),
    ("HX711",     "HX711-M",             (65, 25),       16.0,  24.0,  hx711m_pads()),
    ("TP4056",    "TP4056-PROT-USBC",    (25, 60),       17.3,  29.0,  tp4056_pads()),
    ("TPS63000",  "TPS63000-M",          (65, 60),       16.0,  24.0,  tps63000_pads()),
]


def main() -> int:
    sock = find_pcbnew_socket()
    if not sock:
        print("[HIBA] Nincs /tmp/kicad/api-*.sock -- nyiss egy board-ot a (standalone) PCB Editor-ban.")
        return 1
    print(f"socket: {sock}")

    try:
        k = KiCad(socket_path=sock, client_name="bee_scale-node-modules")
        board = k.get_board()
        print(f"board: {board.name}")

        # Idempotencia: sajat korabbi elemek torlese.
        for group in (board.get_footprints(), board.get_shapes()):
            if group:
                board.remove_items(group)

        created = []
        for ref, value, pos, w, l, pads in MODULES:
            fp = make_module(ref, value, pos, w, l, pads)
            created += board.create_items(fp)

        # Visszaolvasas (a reteg-buktato miatt kotelezo).
        fps = board.get_footprints()
        print(f"\nletrehozott elemek: {len(created)}")
        print(f"footprintek a board-on: {len(fps)}")
        for f in fps:
            npads = len(f.definition.pads)
            nshapes = len(f.definition.shapes)
            print(f"  - {f.value_field.text.value:22} pad:{npads:2d} shape:{nshapes}")

    except (ApiError, KiCadConnectionError) as exc:
        print(f"[HIBA] KiCad IPC: {exc}")
        return 1

    print("\nA 4 modul a PCB Editor-ban lathato. Tologasd oket (M), mentes: Cmd+S.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
