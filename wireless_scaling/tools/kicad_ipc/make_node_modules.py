#!/usr/bin/env python3
"""A node-panel PREMADE breakout-moduljainak footprintjei a futo KiCad PCB
Editor-ba, az IPC API-n (kipy) at -- elrendezes-tervezeshez ("pakolashoz").

A modul-meretek es furatok a KOZOS definiciobol jonnek (node_modules_def.py),
amit a 3D-blokk-generator (attach_module_models.py) is hasznal -> a hordozo-PCB
padjai es a modul 3D-furatai garantaltan szinkronban.

Minden modul egy FootprintInstance:
  - fizikai kontur = BoardRectangle a F.Silkscreen retegen (a modullal egyutt mozog),
  - a SOLDER (forrpont) furatok atmeno-furatos padok (PTH),
  - a MOUNT (mechanikai rogzito) furatok NEM kerulnek a hordozo-PCB-re
    (azok csak a modul 3D blokkjan latszanak) -- ez a felhasznaloi kikotes.

FIGYELEM: ez a script UJRA felrakja a modulokat default pozicioba (create_items) ->
a kezi pakolast felulirja. Ha a footprintek mar a boardon vannak es csak a
3D modellt/furatot akarod frissiteni, az attach_module_models.py-t futtasd
(az pozicio-orzo update_items-et hasznal).

Elofeltetel: fut a KiCad 10, IPC API be, ES nyitva egy board a (standalone) PCB
Editor-ban. A standalone pcbnew sajat socketet nyit (/tmp/kicad/api-<pid>.sock);
ezt auto-detektaljuk (a manager api.sock-ja nem ismeri a GetOpenDocuments-et).

Futtatas:
  python3 make_node_modules.py
"""

import glob
import os
import sys

from kipy import KiCad
from kipy.errors import ApiError, ConnectionError as KiCadConnectionError
from kipy.board_types import (
    FootprintInstance, Pad, PadType, PadStackType, PadStackShape,
    DrillShape, BoardLayer, BoardRectangle,
)
from kipy.geometry import Vector2

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from node_modules_def import MODULES, solder_holes, mount_holes  # noqa: E402


def find_pcbnew_socket():
    socks = sorted(glob.glob("/tmp/kicad/api-*.sock"))
    return ("ipc://" + socks[0]) if socks else None


def tht_pad(number, x_mm, y_mm, pad_d_mm, drill_d_mm) -> Pad:
    """Kor alaku PTH pad. FONTOS: a kipy a pad-poziciot ABSZOLUT board-koordinatakent
    tarolja (fuggetlen a footprint-horgonytol), ezert a hivo mar a horgonnyal
    eltolt (abszolut) koordinatat adja at -- kulonben a modul teste elcsuszik a
    horgonytol, es a hozzarakotott 3D modell nem ul a padokon."""
    pad = Pad()
    pad.number = number
    pad.pad_type = PadType.PT_PTH
    pad.position = Vector2.from_xy_mm(x_mm, y_mm)
    ps = pad.padstack
    ps.type = PadStackType.PST_NORMAL
    fcu = ps.copper_layer(BoardLayer.BL_F_Cu)
    fcu.shape = PadStackShape.PSS_CIRCLE
    fcu.size = Vector2.from_xy_mm(pad_d_mm, pad_d_mm)
    ps.drill.shape = DrillShape.DS_CIRCLE
    ps.drill.diameter = Vector2.from_xy_mm(drill_d_mm, drill_d_mm)
    ps.drill.start_layer = BoardLayer.BL_F_Cu
    ps.drill.end_layer = BoardLayer.BL_B_Cu
    return pad


def silk_outline(cx_mm, cy_mm, w_mm, l_mm) -> BoardRectangle:
    """Kontur-teglalap a F.Silkscreen-en, a (cx,cy) horgonyra centralva (abszolut)."""
    r = BoardRectangle()
    r.top_left = Vector2.from_xy_mm(cx_mm - w_mm / 2, cy_mm - l_mm / 2)
    r.bottom_right = Vector2.from_xy_mm(cx_mm + w_mm / 2, cy_mm + l_mm / 2)
    r.layer = BoardLayer.BL_F_SilkS
    return r


def make_module(value, mod) -> FootprintInstance:
    ox, oy = mod["pos"]                          # horgony = a modul kozeppontja
    fp = FootprintInstance()
    fp.reference_field.text.value = mod["ref"]
    fp.value_field.text.value = value
    fp.layer = BoardLayer.BL_F_Cu               # KOTELEZO (kulonben csendben eldobja)
    fp.position = Vector2.from_xy_mm(ox, oy)
    # A test a horgonyra centralva: minden abszolut koordinata = horgony + relativ.
    fp.definition.add_item(silk_outline(ox, oy, mod["w"], mod["l"]))
    # CSAK a forrpontok kapnak padot a hordozo-PCB-n; a mount furatok kimaradnak.
    for (name, x, y, drill, pad, _kind) in solder_holes(mod):
        fp.definition.add_item(tht_pad(name, ox + x, oy + y, pad, drill))
    return fp


def main() -> int:
    sock = find_pcbnew_socket()
    if not sock:
        print("[HIBA] Nincs pcbnew socket -- nyiss board-ot a (standalone) PCB Editor-ban.")
        return 1
    print(f"socket: {sock}")

    try:
        k = KiCad(socket_path=sock, client_name="bee_scale-node-modules")
        board = k.get_board()
        print(f"board: {board.name}")

        # Idempotencia: sajat korabbi elemek torlese.
        for group in (board.get_footprints(), board.get_shapes()):
            if group:
                board.remove_items(group)

        created = []
        for value, mod in MODULES.items():
            created += board.create_items(make_module(value, mod))

        fps = board.get_footprints()
        print(f"\nletrehozott elemek: {len(created)}")
        print(f"footprintek a board-on: {len(fps)}")
        for f in fps:
            value = f.value_field.text.value
            mod = MODULES.get(value, {})
            ns = len(solder_holes(mod)) if mod else 0
            nm = len(mount_holes(mod)) if mod else 0
            print(f"  - {value:22} pad(solder):{len(f.definition.pads):2d} "
                  f"(def solder:{ns} mount:{nm})")

    except (ApiError, KiCadConnectionError) as exc:
        print(f"[HIBA] KiCad IPC: {exc}")
        return 1

    print("\nA 4 modul a PCB Editor-ban lathato. Tologasd oket (M), mentes: Cmd+S.")
    print("3D furatokhoz/modellhez: attach_module_models.py (pozicio-orzo).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
