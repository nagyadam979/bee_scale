#!/usr/bin/env python3
"""A node-panel premade moduljainak KOZOS definicioja -- egyetlen forras.

Ezt hasznalja a footprint-generator (make_node_modules.py) ES a 3D-blokk-generator
(attach_module_models.py), hogy a hordozo-PCB padjai es a modul 3D-furatai
GARANTALTAN szinkronban legyenek (ugyanabbol a koordinatabol).

Furat-tipusok (`kind`):
  - "solder": forrpont (elektromos lab). -> a hordozo PCB-n PTH pad + furat, ES a 3D blokkon furat.
  - "mount" : mechanikai rogzitofurat (NEM forrpont). -> CSAK a 3D blokkon furat,
              a hordozo PCB-re NEM kerul (se pad, se furat).

Minden koordinata footprint-relativ, mm-ben; az origo a kontur kozepe.
X = szelesseg (w) menten, Y = hosszusag (l) menten.

MERET-BIZTONSAG (2026-07 webkutatas + BOM): csak az ESP32-C3 magas; a HX711-M
sortav/offset becsult, a TP4056/TPS63000 pad-geometria placeholder -> tolomeros
bemeres utan finomitando. A magassagok (h) is becsultek.
"""

PAD_D = 1.8      # alap pad-atmero (solder), mm
DRILL_D = 1.0    # alap furat-atmero, mm


def _row(names, x, pitch=2.54, drill=DRILL_D, pad=PAD_D, kind="solder"):
    """Egy sor egyenkozu lyuk X=x-en, Y-ban centralva a nevek szama szerint."""
    y0 = -(len(names) - 1) * pitch / 2
    return [(nm, x, y0 + i * pitch, drill, pad, kind) for i, nm in enumerate(names)]


def _esp32c3_holes():
    # 2x8 @2,54, sortav 15,24 (x=+-7,62). Sorok a hosszu (22,5) elek menten.
    left = _row([str(i) for i in range(1, 9)], -7.62)
    right = _row([str(i) for i in range(9, 17)], 7.62)
    return left + right


def _hx711m_holes():
    # analog 6 (x=-6,5) + digitalis 4 (x=+6,5), @2,54. Sortav ~13 (BECSLES).
    analog = _row(["E+", "E-", "A-", "A+", "B-", "B+"], -6.5)
    digital = _row(["GND", "DT", "SCK", "VCC"], 6.5)
    return analog + digital


def _tp4056_holes():
    # NEM raszter. USB-veg: IN+/IN-; tulso veg: OUT+/B+/B-/OUT- (3,4/7,6/3,4).
    return [
        ("IN+", -7.1, -12.8, DRILL_D, PAD_D, "solder"),
        ("IN-", 7.1, -12.8, DRILL_D, PAD_D, "solder"),
        ("OUT+", -7.2, 12.8, DRILL_D, PAD_D, "solder"),
        ("B+", -3.8, 12.8, DRILL_D, PAD_D, "solder"),
        ("B-", 3.8, 12.8, DRILL_D, PAD_D, "solder"),
        ("OUT-", 7.2, 12.8, DRILL_D, PAD_D, "solder"),
    ]


def _tps63000_holes():
    # 4 sarok-tappad (nagyobb) + also konfig-padek (kicsi). BECSLES.
    corners = [
        ("VIN", -5.5, -9.5, 1.2, 2.2, "solder"),
        ("VOUT", 5.5, -9.5, 1.2, 2.2, "solder"),
        ("GND1", -5.5, 9.5, 1.2, 2.2, "solder"),
        ("GND2", 5.5, 9.5, 1.2, 2.2, "solder"),
    ]
    # also el menti konfig-sor: X=-4,5..+4,5 (pitch 1,8), Y=+10,5, kis padek.
    cfg_names = ["EN", "PS", "5V", "4V2", "3V3", "ADJ"]
    x0 = -(len(cfg_names) - 1) * 1.8 / 2
    cfg = [(nm, x0 + i * 1.8, 10.5, 0.7, 1.2, "solder")
           for i, nm in enumerate(cfg_names)]
    return corners + cfg


# value_field -> modul-definicio
MODULES = {
    "ESP32-C3 SuperMini": dict(ref="ESP32C3", pos=(25, 25), w=18.0, l=22.5, h=4.5,
                               step="esp32c3.step", holes=_esp32c3_holes()),
    "HX711-M":            dict(ref="HX711", pos=(65, 25), w=16.0, l=24.0, h=3.0,
                               step="hx711m.step", holes=_hx711m_holes()),
    "TP4056-PROT-USBC":   dict(ref="TP4056", pos=(25, 60), w=17.3, l=29.0, h=4.3,
                               step="tp4056.step", holes=_tp4056_holes()),
    "TPS63000-M":         dict(ref="TPS63000", pos=(65, 60), w=16.0, l=24.0, h=4.0,
                               step="tps63000.step", holes=_tps63000_holes()),
}


def solder_holes(mod):
    return [h for h in mod["holes"] if h[5] == "solder"]


def mount_holes(mod):
    return [h for h in mod["holes"] if h[5] == "mount"]
